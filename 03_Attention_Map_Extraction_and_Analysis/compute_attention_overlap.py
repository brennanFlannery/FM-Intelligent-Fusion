#!/usr/bin/env python3
"""
Compute Dice score overlaps between attention maps from different foundation models.

This script analyzes attention maps generated by the extract_attention_maps.py script
and computes Dice score overlaps between every pair of the 5 foundation models:
- MUSK
- CONCH v1.5  
- Virchow2
- H-optimus1
- GigaPath

The script supports two modes:
1. Fixed threshold mode: Uses a fixed threshold (default: 0.5) to binarize attention maps
2. Percentile mode: Uses percentile-based thresholding (default: 50th, 60th, 70th, 80th, 90th percentiles)

The script outputs:
1. A CSV file with Dice scores for all model pairs
2. Heatmap visualizations of the overlap scores
3. 5 random example tiles with attention map overlays for each model (saved as PNG files)

Usage:
    # Fixed threshold mode
    python compute_attention_overlap.py --parent-folder /path/to/parent/folder --threshold 0.5
    
    # Percentile mode (recommended)
    python compute_attention_overlap.py --parent-folder /path/to/parent/folder --percentile-mode --percentiles 50.0 60.0 70.0 80.0 90.0
    
    # Simple mode (for attention maps from --simple flag in extract_attention_maps.py)
    python compute_attention_overlap.py --parent-folder /path/to/parent/folder --percentile-mode --simple
"""

