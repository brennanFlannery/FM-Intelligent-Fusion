def main():
    """Main function to compute attention overlaps."""
    parser = argparse.ArgumentParser(
        description="Compute Dice score overlaps between attention maps from different foundation models"
    )
    parser.add_argument(
        "--parent-folder", "-p",
        type=str,
        required=True,
        help="Path to parent folder containing model subdirectories and Original folder"
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=0.5,
        help="Threshold for converting attention maps to binary masks (default: 0.5)"
    )
    parser.add_argument(
        "--percentile-mode",
        action="store_true",
        help="Use percentile-based thresholding instead of fixed threshold"
    )
    parser.add_argument(
        "--percentiles",
        type=float,
        nargs='+',
        default=[50.0, 60.0, 70.0, 80.0, 90.0],
        help="Percentiles to test when using percentile mode (default: 50.0 60.0 70.0 80.0 90.0)"
    )
    parser.add_argument(
        "--num-examples",
        type=int,
        default=5,
        help="Number of random example overlays to generate per model (default: 5)"
    )
    parser.add_argument(
        "--colormap",
        type=str,
        default="hot",
        help="Colormap for attention overlays (default: hot)"
    )
    parser.add_argument(
        "--test",
        action="store_true",
        help="Test mode: only process first 1000 tiles for faster execution"
    )
    parser.add_argument(
        "--blur",
        action="store_true",
        help="Apply blurring to attention maps before computing Dice scores"
    )
    parser.add_argument(
        "--blur-method",
        type=str,
        default="gaussian",
        choices=["gaussian", "uniform", "median"],
        help="Blur method to use when --blur is enabled (default: gaussian)"
    )
    parser.add_argument(
        "--blur-strength",
        type=float,
        default=1.0,
        help="Blur strength (sigma for gaussian, radius for others) when --blur is enabled (default: 1.0)"
    )
    parser.add_argument(
        "--simple",
        action="store_true",
        help="Search for attention maps in 'simple' subdirectories (from --simple mode in extract_attention_maps.py)"
    )
    
    args = parser.parse_args()
    
    # Convert to Path objects
    parent_folder = Path(args.parent_folder)
    
    if not parent_folder.exists():
        raise FileNotFoundError(f"Parent folder not found: {parent_folder}")
    
    # Define the 5 foundation models
    models = ["musk", "conch_v15", "virchow2", "hoptimus1", "gigapath"]
    
    print(f"Analyzing attention maps in: {parent_folder}")
    print(f"Models: {', '.join(models)}")
    if args.test:
        print("TEST MODE: Processing only first 1000 tiles")
    if args.blur:
        print(f"BLUR MODE: Applying {args.blur_method} blur (strength={args.blur_strength})")
    if args.percentile_mode:
        print(f"PERCENTILE MODE: Testing percentiles {args.percentiles}")
    else:
        print(f"FIXED THRESHOLD MODE: Using threshold {args.threshold}")
    if args.simple:
        print("SIMPLE MODE: Searching in 'simple' subdirectories")
    
    # Check that all model directories exist
    missing_models = []
    for model in models:
        model_dir = parent_folder / model
        if not model_dir.exists():
            missing_models.append(model)
    
    if missing_models:
        print(f"Warning: Missing model directories: {missing_models}")
        models = [m for m in models if m not in missing_models]
    
    if len(models) < 2:
        raise ValueError("Need at least 2 models to compute overlaps")
    
    print(f"Using models: {', '.join(models)}")
    
    # Find common tiles
    print("\nFinding common tiles...")
    max_tiles = 1000 if args.test else None
    common_tiles = find_common_tiles(parent_folder, models, max_tiles, args.simple)
    print(f"Found {len(common_tiles)} tiles common to all models")
    
    if len(common_tiles) == 0:
        raise ValueError("No common tiles found across all models")
    
    # Compute Dice overlaps
    if args.percentile_mode:
        print(f"\nComputing Dice scores with percentiles {args.percentiles}...")
        dice_scores = compute_dice_overlaps_percentile(
            parent_folder, models, common_tiles, args.percentiles,
            blur_enabled=args.blur, blur_method=args.blur_method, blur_strength=args.blur_strength,
            simple_mode=args.simple
        )
        
        # Save results to CSV
        csv_path = parent_folder / "attention_overlap_dice_scores_percentile.csv"
        save_dice_results_csv_percentile(dice_scores, csv_path)
        
        # Create heatmap visualization
        heatmap_path = parent_folder / "attention_overlap_heatmap_percentile.png"
        create_dice_heatmap_percentile(dice_scores, heatmap_path)
    else:
        print(f"\nComputing Dice scores with threshold {args.threshold}...")
        dice_scores = compute_dice_overlaps(
            parent_folder, models, common_tiles, args.threshold,
            blur_enabled=args.blur, blur_method=args.blur_method, blur_strength=args.blur_strength,
            simple_mode=args.simple
        )
        
        # Save results to CSV
        csv_path = parent_folder / "attention_overlap_dice_scores.csv"
        save_dice_results_csv(dice_scores, csv_path)
        
        # Create heatmap visualization
        heatmap_path = parent_folder / "attention_overlap_heatmap.png"
        create_dice_heatmap(dice_scores, heatmap_path)
    
    # Generate example overlays
    print(f"\nGenerating {args.num_examples} example overlays per model...")
    generate_example_overlays(parent_folder, models, common_tiles, args.num_examples)
    
    print("\nAnalysis complete!")
    print(f"Results saved in: {parent_folder}")
    print(f"  - Dice scores CSV: {csv_path}")
    print(f"  - Heatmap visualization: {heatmap_path}")
    print(f"  - Example overlays: {args.num_examples} per model")


